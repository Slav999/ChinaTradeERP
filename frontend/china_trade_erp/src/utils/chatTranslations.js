const ru = Object.fromEntries(Object.entries(en).map(([russian, english]) => [english, russian]))
const patterns = [
  [/^(\d+) участников$/, m => `${m[1]} ${m[1] === '1' ? 'member' : 'members'}`],
  [/^Прочитали (\d+) из (\d+)$/, m => `Read by ${m[1]} of ${m[2]}`],
  [/^Прочитано (.+)$/, m => `Read ${m[1]}`], [/^Реакция (.+)$/, m => `Reaction ${m[1]}`],
  [/^Файлы \((\d+)\)$/, m => `Files (${m[1]})`], [/^Загрузка (\d+)%$/, m => `Uploading ${m[1]}%`],
  [/^Убрать (.+) из группы$/, m => `Remove ${m[1]} from group`], [/^Убрать (.+)$/, m => `Remove ${m[1]}`],
  [/^В архив: (.+)$/, m => `Archive: ${m[1]}`], [/^Вернуть из архива: (.+)$/, m => `Restore from archive: ${m[1]}`],
  [/^Ответ: (.+)$/, m => `Reply to: ${m[1]}`], [/^Кому отправить:$/, () => 'Send to:'],
  [/^Обсуждения:$/, () => 'Discussions:'], [/^… Полный список — в меню ⋯$/, () => '… Full list in the ⋯ menu'],
  [/^Закреплено · (\d+) —$/, m => `Pinned · ${m[1]} —`],
  [/^Файлы компании: (.+) из (.+)$/, m => `Company files: ${m[1]} of ${m[2]}`.replace(/КБ|МБ|ГБ/g, unit => ({ КБ: 'KB', МБ: 'MB', ГБ: 'GB' })[unit])],
  [/^(.+) передал\(а\) управление группой (.+)\.$/, m => `${m[1]} transferred group ownership to ${m[2]}.`],
  [/^(.+) создал\(а\) группу «(.*)»\.$/, m => `${m[1]} created the group “${m[2]}”.`],
  [/^(.+) изменил\(а\) название группы на «(.*)»\.$/, m => `${m[1]} renamed the group to “${m[2]}”.`],
  [/^(.+) добавил\(а\) (.+) в группу\.$/, m => `${m[1]} added ${m[2]} to the group.`],
  [/^(.+) удалил\(а\) (.+) из группы\.$/, m => `${m[1]} removed ${m[2]} from the group.`],
  [/^(.+) вышел\(ла\) из группы\.$/, m => `${m[1]} left the group.`],
  [/^(.+) (КБ|МБ|ГБ)$/, m => `${m[1]} ${{ КБ: 'KB', МБ: 'MB', ГБ: 'GB' }[m[2]]}`],
]

export function translateChatText(value, locale) {
  const source = value.trim(), dictionary = locale === 'en' ? en : ru
  if (dictionary[source]) return value.replace(source, dictionary[source])
  if (locale === 'en') {
    for (const [pattern, render] of patterns) {
      const match = source.match(pattern)
      if (match) return value.replace(source, render(match))
    }
  }
  return value
}

export function chatReferenceTitle(record, locale) {
  const title = record?.title || ''
  if (record?.unavailable) return translateChatText(title, locale)
  if (locale !== 'en' || !['customer_order', 'supplier_order'].includes(record?.type)) return title
  return title.replace(/^(Заказ покупателя|Заказ поставщику|Командировка \/ образцы)(?=\s|$)/, label => en[label])
}
